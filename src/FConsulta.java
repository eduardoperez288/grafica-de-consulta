    private void CLIKActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CLIKActionPerformed

        String query = "SELECT DATE_FORMAT(fecha, '%Y-%m') AS mes, "
                + "ROUND(AVG(nvl_glucosa), 1) AS promedio "
                + "FROM mediciones "
                + "GROUP BY DATE_FORMAT(fecha, '%Y-%m') "
                + "ORDER BY mes";

        datos = cnx.consultar(query);
        System.out.println("Filas: " + datos.size());   // para depurar
        series.clear();
        series.add("Glucosa promedio");

        panel.removeAll();
        panel.setLayout(new java.awt.BorderLayout());        // clave
        chart = new GraficaXY("Glucosa promedio por mes",
                "Mes", "mg/dL", series, datos);
        panel.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        panel.revalidate();
        panel.repaint();

        cnx.entablar(query, TQuery, 60, 40);
    

    }//GEN-LAST:event_CLIKActionPerformed

